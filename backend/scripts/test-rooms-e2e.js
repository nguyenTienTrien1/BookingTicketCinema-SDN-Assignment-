import 'dotenv/config';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import User from '../src/models/User.js';
import CinemaRoom from '../src/models/CinemaRoom.js';
import Movie from '../src/models/Movie.js';
import Showtime from '../src/models/Showtime.js';
import { createBooking } from '../src/services/bookingService.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dbName = 'cinema_rooms_browser_' + randomUUID().replaceAll('-', '');
let vite, server, browser, page, stage = 'setup', checks = 0;
const check = (value, description) => { assert.ok(value, description); checks++; };
process.env.NODE_ENV = 'test';
await mongoose.connect(process.env.MONGODB_URI, { dbName, serverSelectionTimeoutMS: 5000 });
try {
  const password = randomUUID();
  await User.create({ fullName: 'Rooms Browser Admin', email: 'admin@rooms-browser.test', password, role: 'admin', status: 'Active' });
  const member = await User.create({ fullName: 'Rooms Browser Member', email: 'member@rooms-browser.test', password: randomUUID(), role: 'member', status: 'Active' });
  const movie = await Movie.create({ title: 'Rooms Browser Movie', classification: 'P', duration: 90 });
  const other = await CinemaRoom.create({ cinema: 'Other Cinema', name: 'Other Room', status: 'Maintenance', seats: ['A1'] });
  const { default: app } = await import('../src/app.js');
  server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
  vite = await createServer({ root: path.join(root, 'frontend'), configFile: false, plugins: [react()], logLevel: 'silent',
    define: { 'import.meta.env.VITE_API_URL': JSON.stringify('/api') },
    server: { host: '127.0.0.1', port: 0, open: false, proxy: { '/api': `http://127.0.0.1:${server.address().port}` } } });
  await vite.listen();
  const base = `http://127.0.0.1:${vite.httpServer.address().port}`;
  process.env.CORS_ORIGIN = base;
  browser = await chromium.launch({ channel: process.env.E2E_BROWSER_CHANNEL || 'msedge', headless: true });
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('Failed to load resource')) errors.push(message.text()); });
  page.setDefaultTimeout(10000);
  const artifacts = path.join(root, '.local', 'qa', 'rooms');
  await mkdir(artifacts, { recursive: true });
  async function visible(text) { await page.getByText(text, { exact: true }).waitFor(); checks++; }
  const seat = number => page.getByRole('button', { name: new RegExp('^' + number + ',') });
  async function saveLayout() {
    await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).click();
    await page.getByRole('button', { name: 'Xác nhận và lưu', exact: true }).click();
    await visible('Đã lưu cấu hình ghế.');
  }
  stage = 'real login and room creation';
  await page.goto(base + '/admin/rooms');
  await page.locator('#cinema-email').fill('admin@rooms-browser.test');
  await page.locator('#cinema-password').fill(password);
  await page.locator('button[type="submit"]').click();
  await page.getByRole('heading', { name: 'Quản lý phòng chiếu', exact: true }).waitFor(); checks++;
  await visible('Other Room');
  await page.getByRole('button', { name: '+ Thêm phòng', exact: true }).click();
  const editor = page.locator('.roomEditorPanel');
  const creationStatuses = await editor.getByLabel('Trạng thái', { exact: true }).locator('option').evaluateAll(options => options.map(option => ({ value: option.value, label: option.textContent })));
  assert.deepEqual(creationStatuses, [{ value: 'Active', label: 'Hoạt động' }, { value: 'Inactive', label: 'Chưa hoạt động' }]); checks++;
  await editor.getByLabel('Rạp', { exact: true }).fill('Browser Cinema');
  await editor.getByLabel('Tên phòng', { exact: true }).fill('Browser Room');
  await editor.getByLabel('Số hàng', { exact: true }).fill('2');
  await editor.getByLabel('Ghế mỗi hàng', { exact: true }).fill('3');
  await editor.getByRole('button', { name: 'Lưu phòng', exact: true }).click();
  await visible('Đã tạo phòng chiếu.');
  const created = await CinemaRoom.findOne({ name: 'Browser Room' });
  check(created.status === 'Inactive' && created.seats.length === 6, 'Creation stores a valid inactive room and layout');
  const createdRow = page.getByRole('row').filter({ hasText: 'Browser Room' });
  await createdRow.getByText('Chưa hoạt động', { exact: true }).waitFor(); checks++;
  await page.reload();
  await page.getByRole('row').filter({ hasText: 'Browser Room' }).getByText('Chưa hoạt động', { exact: true }).waitFor(); checks++;
  await page.screenshot({ path: path.join(artifacts, 'list-colors.png'), fullPage: true });

  stage = 'list search filters and room edit';
  await page.getByLabel('Tìm phòng', { exact: true }).fill('Browser Room');
  await page.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  await visible('1 phòng chiếu');
  await page.getByRole('button', { name: 'Sửa Browser Room', exact: true }).click();
  check(await editor.getByLabel('Trạng thái', { exact: true }).locator('option[value="Inactive"]').textContent() === 'Ngừng hoạt động', 'Edit form keeps the inactive label requested for existing rooms');
  await editor.getByLabel('Trạng thái', { exact: true }).selectOption('Active');
  await editor.getByRole('button', { name: 'Lưu phòng', exact: true }).click();
  await visible('Đã cập nhật phòng chiếu.');
  await page.getByLabel('Trạng thái', { exact: true }).selectOption('Maintenance');
  await visible('Chưa có phòng phù hợp');
  await page.getByLabel('Trạng thái', { exact: true }).selectOption('Active');
  await visible('Browser Room');
  await page.getByLabel('Rạp', { exact: true }).selectOption('Other Cinema');
  await visible('Chưa có phòng phù hợp');
  await page.getByLabel('Rạp', { exact: true }).selectOption('Browser Cinema');
  await visible('Browser Room');

  stage = 'bulk selection keyboard and seat properties';
  await page.getByRole('link', { name: 'Cấu hình ghế', exact: true }).click();
  await seat('A1').waitFor();
  await seat('A1').focus(); await page.keyboard.press('Space');
  check(await seat('A1').getAttribute('aria-pressed') === 'true', 'Keyboard can select a seat');
  await seat('A2').click();
  check(await seat('A2').getAttribute('aria-pressed') === 'true', 'Multiple seats selected');
  await page.getByLabel('Loại ghế', { exact: true }).selectOption('VIP');
  await page.getByRole('button', { name: 'Áp dụng loại ghế', exact: true }).click();
  check(await seat('A1').getAttribute('aria-pressed') === 'false' && await seat('A2').getAttribute('aria-pressed') === 'false', 'Applying type clears the completed selection');
  check(await page.getByRole('button', { name: 'Áp dụng loại ghế', exact: true }).isDisabled(), 'Type action requires a new selection');
  await seat('B1').click();
  await page.getByLabel('Loại ghế', { exact: true }).selectOption('Standard');
  await page.getByRole('button', { name: 'Áp dụng loại ghế', exact: true }).click();
  check((await seat('A1').getAttribute('aria-label')).includes('VIP') && (await seat('A2').getAttribute('aria-label')).includes('VIP'), 'Changing another group type does not alter the completed group');
  await seat('A1').click();
  await seat('A2').click();
  await page.getByLabel('Tình trạng vận hành', { exact: true }).selectOption('Broken');
  await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).click();
  check(await seat('A1').getAttribute('aria-pressed') === 'false' && await seat('A2').getAttribute('aria-pressed') === 'false', 'Applying condition clears the completed selection');
  check(await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).isDisabled(), 'Condition action requires a new selection');
  await seat('B1').click();
  await page.getByLabel('Tình trạng vận hành', { exact: true }).selectOption('Maintenance');
  await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).click();
  check((await seat('A1').getAttribute('aria-label')).includes('Hư hỏng') && (await seat('A2').getAttribute('aria-label')).includes('Hư hỏng'), 'Changing another group condition does not alter the completed group');
  check((await seat('B1').getAttribute('aria-label')).includes('Đang sửa chữa'), 'Only the newly selected group changes condition');
  await seat('B1').click();
  await page.getByLabel('Tình trạng vận hành', { exact: true }).selectOption('Active');
  await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).click();
  const beforeSave = await CinemaRoom.findById(created._id);
  check(beforeSave.seatConfigs.get('A1').type === 'Standard' && beforeSave.seatConfigs.get('A1').status === 'Active', 'Editing remains local before save');
  await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).click();
  await visible('Đổi loại (2)'); await visible('Đổi tình trạng (2)');
  check(await page.locator('#seat-review-title').evaluate(element => element === document.activeElement), 'Review receives keyboard focus');
  await page.getByRole('button', { name: 'Xác nhận và lưu', exact: true }).click();
  await visible('Đã lưu cấu hình ghế.');
  let current = await CinemaRoom.findById(created._id);
  check(current.seatConfigs.get('A1').type === 'VIP' && current.seatConfigs.get('A2').status === 'Broken', 'Bulk type/condition persisted');

  stage = 'cancel draft and identifier add remove';
  await seat('A1').click();
  await page.getByLabel('Tình trạng vận hành', { exact: true }).selectOption('Maintenance');
  await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).click();
  await page.getByRole('link', { name: 'Hủy và về danh sách', exact: true }).click();
  check((await CinemaRoom.findById(created._id)).seatConfigs.get('A1').status === 'Broken', 'Cancel discards changes');
  await page.getByRole('row').filter({ hasText: 'Browser Room' }).getByRole('link', { name: 'Cấu hình ghế', exact: true }).click();
  await seat('A1').click();
  await page.getByLabel('Mã ghế', { exact: true }).fill('C1');
  await page.getByRole('button', { name: 'Đổi mã ghế', exact: true }).click();
  check(await seat('C1').isVisible(), 'Seat identifier renamed in draft');
  await page.getByLabel('Mã ghế mới', { exact: true }).fill('D1');
  await page.getByRole('button', { name: 'Thêm ghế', exact: true }).click();
  await page.getByRole('button', { name: 'Xóa ghế đã chọn', exact: true }).click();
  check(await seat('C1').count() === 0, 'Selected position removed');
  await saveLayout();
  current = await CinemaRoom.findById(created._id);
  check(current.seats.includes('D1') && !current.seats.includes('A1'), 'Added/deleted identifiers persist');

  stage = 'layout generator and review cancellation';
  await page.getByLabel('Hàng (A–Z)', { exact: true }).fill('2');
  await page.getByLabel('Ghế mỗi hàng', { exact: true }).fill('3');
  await page.getByRole('button', { name: 'Tạo lại sơ đồ', exact: true }).click();
  await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).click();
  await page.getByRole('button', { name: 'Quay lại chỉnh sửa', exact: true }).click();
  check((await CinemaRoom.findById(created._id)).seats.includes('D1'), 'Cancelling review does not save');
  await saveLayout();
  check((await CinemaRoom.findById(created._id)).seats.includes('A1'), 'Generated layout saved');

  stage = 'protected seat conflict and save-time recheck';
  const showResponse = await page.request.post(base + '/api/showtimes', { data: { movie: String(movie._id), cinema: 'Browser Cinema', room: 'Browser Room', price: 80000, startTime: new Date(Date.now() + 3600000).toISOString() } });
  check(showResponse.status() === 201, 'Actual scheduling API accepts configured room');
  const show = (await showResponse.json()).showtime;
  await createBooking({ userId: member._id, showtimeId: show._id, seats: ['A1'] });
  await seat('A1').click();
  await page.getByLabel('Tình trạng vận hành', { exact: true }).selectOption('Broken');
  await page.getByRole('button', { name: 'Áp dụng tình trạng', exact: true }).click();
  await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).click();
  await visible('Không thể lưu cấu hình này');
  check(await page.getByRole('button', { name: 'Xác nhận và lưu', exact: true }).isDisabled(), 'Conflict blocks confirmation');
  await page.screenshot({ path: path.join(artifacts, 'protected-conflict.png'), fullPage: true });
  await page.getByRole('button', { name: 'Quay lại chỉnh sửa', exact: true }).click();
  await page.reload();
  await seat('B1').click();
  await page.getByLabel('Loại ghế', { exact: true }).selectOption('VIP');
  await page.getByRole('button', { name: 'Áp dụng loại ghế', exact: true }).click();
  await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).click();
  check(await page.getByRole('button', { name: 'Xác nhận và lưu', exact: true }).isEnabled(), 'Preview initially has no conflict');
  await createBooking({ userId: member._id, showtimeId: show._id, seats: ['B1'] });
  await page.getByRole('button', { name: 'Xác nhận và lưu', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Ghế B1' }).waitFor(); checks++;
  check((await CinemaRoom.findById(created._id)).seatConfigs.get('B1').type === 'Standard', 'Late hold rejects save without changing metadata');

  stage = 'responsive screenshots and deletion';
  await page.getByRole('button', { name: 'Tải lại phòng và bỏ bản nháp', exact: true }).click();
  await seat('A1').waitFor();
  for (const [width, height] of [[1440, 1000], [768, 1024], [375, 812], [667, 375]]) {
    await page.setViewportSize({ width, height });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal page overflow');
    await page.getByRole('button', { name: 'Xem lại thay đổi', exact: true }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(artifacts, `editor-${width}x${height}.png`), fullPage: true });
  }
  await page.goto(base + '/admin/rooms');
  await page.getByRole('button', { name: 'Xóa Other Room', exact: true }).click();
  await page.locator('.roomEditorPanel').getByRole('button', { name: 'Hủy', exact: true }).click();
  check(Boolean(await CinemaRoom.findById(other._id)), 'Delete cancellation preserves room');
  await page.getByRole('button', { name: 'Xóa Other Room', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận xóa', exact: true }).click();
  await visible('Đã xóa phòng chiếu.'); check(!await CinemaRoom.findById(other._id), 'Delete removes unreferenced room');
  await page.getByRole('button', { name: 'Xóa Browser Room', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận xóa', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Phòng đã có suất chiếu' }).waitFor(); checks++;
  check(Boolean(await Showtime.findById(show._id)), 'Blocked deletion preserves scheduled showtime');
  check(errors.length === 0, 'No browser console/runtime errors: ' + errors.join('; '));
  console.log(JSON.stringify({ result: 'passed', checks, artifacts, actualApiAndDatabase: true }));
} catch (error) {
  console.error('Room browser check failed at: ' + stage);
  if (page) {
    console.error(await page.locator('.movieAdmin').innerText());
    await page.screenshot({ path: path.join(root, '.local', 'qa', 'rooms', 'failure.png'), fullPage: true });
  }
  throw error;
} finally {
  if (browser) await browser.close();
  if (vite) await vite.close();
  if (server) await new Promise(resolve => server.close(resolve));
  assert.equal(mongoose.connection.name, dbName);
  await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
}
