import 'dotenv/config';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import jwt from 'jsonwebtoken';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import User from '../src/models/User.js';
import Movie from '../src/models/Movie.js';
import Showtime from '../src/models/Showtime.js';
import Booking from '../src/models/Booking.js';
import PaymentAttempt from '../src/models/PaymentAttempt.js';
import RevenueEntry from '../src/models/RevenueEntry.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const artifacts = path.join(root, '.local/qa/ticket-design');
const dbName = 'cinema_ticket_design_' + randomUUID().replaceAll('-', '');
process.env.NODE_ENV = 'test';
let browser, vite, server, page, checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; };
await mongoose.connect(process.env.MONGODB_URI, { dbName, serverSelectionTimeoutMS: 5000 });
try {
    await Promise.all([Booking.init(), RevenueEntry.init(), PaymentAttempt.init()]);
    const member = await User.create({ fullName: 'Ticket Design Member', email: 'ticket-design@test.local', password: randomUUID(), role: 'member', status: 'Active' });
    const employee = await User.create({ fullName: 'Ticket Design Staff', email: 'ticket-staff@test.local', password: randomUUID(), role: 'employee', status: 'Active' });
    const movie = await Movie.create({ title: 'DUNE: HÀNH TINH CÁT', poster: '/src/assets/posters/dune.jpg', banner: '/src/assets/posters/dune.jpg', duration: 166, classification: 'T13' });
    async function fixture(state = 'paid', offset = 120) {
        const id = new mongoose.Types.ObjectId(), ref = randomUUID();
        const showtime = await Showtime.create({ movie: movie.id, cinema: 'CINEMA+ Vincom Đồng Khởi', room: 'Phòng 03 · IMAX', price: 103050, startTime: new Date(Date.now() + offset * 60000), seats: ['A4', 'A5'].map(number => ({ number, status: state === 'paid' ? 'booked' : 'held', bookingId: id })) });
        const booking = await Booking.create({ _id: id, user: member.id, showtime: showtime.id, seats: ['A4', 'A5'], subtotal: 206100, total: 206100, status: state === 'paid' ? 'paid' : 'pending', paymentStatus: state === 'paid' ? 'paid' : 'unpaid', paymentMethod: 'vnpay', paymentRef: state === 'paid' ? ref : undefined, expiresAt: new Date(Date.now() + 600000), paidAt: state === 'paid' ? new Date() : undefined, ticketMode: 'verified', ticketContext: { movieTitle: movie.title, cinema: showtime.cinema, room: showtime.room, startTime: showtime.startTime, classification: 'T13' }, tickets: state === 'paid' ? ['A4', 'A5'].map(seat => ({ seat, reference: 'CT-' + randomUUID().replaceAll('-', '').toUpperCase(), status: 'issued', issuedAt: new Date() })) : [] });
        await PaymentAttempt.create({ ref, booking: id, amount: 206100, method: 'vnpay', status: state === 'paid' ? 'succeeded' : state === 'failed' ? 'failed' : 'created', ...(state === 'paid' ? { providerRef: randomUUID() } : {}) });
        if (state === 'paid') await RevenueEntry.create({ booking: id, kind: 'payment', reference: ref, method: 'vnpay', evidence: 'provider-confirmation', confirmedAt: new Date(), gross: 206100, amount: 206100 });
        return { booking, showtime, ref };
    }
    const paid = await fixture(), pending = await fixture('pending'), failed = await fixture('failed'), expired = await fixture('paid', -60);
    const { default: app } = await import('../src/app.js');
    server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
    vite = await createServer({ root: path.join(root, 'frontend'), configFile: false, plugins: [react()], logLevel: 'silent', define: { 'import.meta.env.VITE_API_URL': JSON.stringify('/api'), 'import.meta.env.VITE_GOOGLE_CLIENT_ID': JSON.stringify('') }, server: { host: '127.0.0.1', port: 0, proxy: { '/api': `http://127.0.0.1:${server.address().port}` } } });
    await vite.listen(); const base = `http://127.0.0.1:${vite.httpServer.address().port}`;
    browser = await chromium.launch({ channel: process.env.E2E_BROWSER_CHANNEL || 'msedge', headless: true });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce' });
    async function authenticate(user) { await context.addCookies([{ name: 'token', value: jwt.sign({ id: user.id, tokenVersion: user.tokenVersion || 0 }, process.env.JWT_SECRET || 'supersecret_cinema_jwt_key_2026_sdn302', { expiresIn: '5m' }), url: base, httpOnly: true }]); }
    await authenticate(member); page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', e => errors.push(e.message)); await mkdir(artifacts, { recursive: true });
    const before = await Booking.findById(paid.booking.id).lean();
    await page.goto(`${base}/payment-result?reference=${paid.ref}`);
    await page.getByRole('heading', { name: 'Thanh toán thành công!' }).waitFor();
    await page.getByRole('img', { name: 'QR vé ghế A5', exact: true }).waitFor();
    check(await page.locator('.cinemaSeatTicket').count() === 2, 'Success shows a separate ticket per seat');
    check(await page.locator('.cinemaPaidAmount').innerText() === '206.100đ', 'Confirmed amount is displayed');
    check(await page.locator('.cinemaHeroPoster img').evaluate(img => img.complete && img.naturalWidth > 0), 'Real movie poster loads');
    check(await page.locator('.cinemaPageBackdrop img').getAttribute('src') === movie.banner, 'Movie image is the page background');
    const sources = await page.locator('.cinemaTicketQrArea img').evaluateAll(imgs => imgs.map(img => img.src));
    check(new Set(sources).size === 2, 'Seats have distinct QR images');
    const downloadEvent = page.waitForEvent('download'); await page.locator('.cinemaTicketBottom a').first().click();
    check((await downloadEvent).suggestedFilename() === 've-ghe-A4.png', 'Each QR can be downloaded');
    await page.screenshot({ path: path.join(artifacts, 'payment-success-desktop.png'), fullPage: true });
    await page.getByRole('link', { name: 'Chi tiết vé & check-in →' }).click();
    await page.getByRole('heading', { name: 'Vé QR theo từng ghế' }).waitFor();
    await page.getByRole('img', { name: 'QR vé ghế A5', exact: true }).waitFor();
    check(await page.locator('.cinemaHeroPoster img').getAttribute('src') === movie.poster, 'QR detail receives movie artwork from owned API');
    check(await page.locator('.cinemaTicketBookingMeta').innerText().then(text => text.includes(paid.booking.id)), 'Booking reference is visible');
    await page.screenshot({ path: path.join(artifacts, 'seat-tickets-desktop.png'), fullPage: true });
    await Booking.updateOne({ _id: paid.booking.id }, { $set: { 'tickets.0.status': 'checked-in', 'tickets.0.checkedInAt': new Date() } });
    await page.getByRole('button', { name: /Làm mới trạng thái/ }).click();
    await page.locator('.cinemaSeatTicket--checked-in').waitFor();
    check(await page.locator('.cinemaSeatTicket--checked-in img').count() === 0, 'Checked-in seat never displays a reusable QR');
    check(await page.getByRole('img', { name: 'QR vé ghế A5', exact: true }).count() === 1, 'Other seat keeps its own QR');
    for (const width of [390, 360]) {
        await page.setViewportSize({ width, height: 844 });
        check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Ticket detail fits ${width}px without overflow`);
    }
    await page.screenshot({ path: path.join(artifacts, 'seat-tickets-mobile.png'), fullPage: true });
    await page.goto(`${base}/payment-result?reference=${paid.ref}`);
    await page.locator('.cinemaSeatTicket--checked-in').waitFor();
    check(await page.locator('.cinemaSeatTicket--checked-in img').count() === 0, 'Payment success also respects check-in state');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Payment success fits mobile');
    await page.screenshot({ path: path.join(artifacts, 'payment-success-mobile.png'), fullPage: true });
    await page.goto(`${base}/bookings/${expired.booking.id}/tickets`);
    await page.locator('.cinemaSeatTicket--expired').first().waitFor();
    check(await page.locator('.cinemaTicketQrArea img').count() === 0, 'Expired tickets show status instead of QR');
    await page.goto(`${base}/payment-result?reference=${pending.ref}`);
    await page.getByRole('heading', { name: 'Đang xác nhận thanh toán' }).waitFor();
    check(await page.locator('.cinemaSeatTicket').count() === 0, 'Pending payment does not expose tickets');
    await page.goto(`${base}/payment-result?reference=${failed.ref}`);
    await page.getByRole('heading', { name: 'Thanh toán chưa hoàn tất' }).waitFor();
    check(await page.locator('.cinemaSeatTicket').count() === 0, 'Failed payment does not expose tickets');
    await Booking.updateOne({ _id: expired.booking.id }, { $set: { status: 'refunded', paymentStatus: 'refunded', refund: { reference: expired.ref, status: 'completed', points: 206.1 } } });
    await page.goto(`${base}/payment-result?reference=${expired.ref}`);
    await page.getByRole('heading', { name: 'Đã hoàn về điểm thành viên' }).waitFor();
    check(await page.locator('.cinemaSeatTicket').count() === 0, 'Refunded payment never shows usable tickets');
    await page.goto(base + '/payment-result'); await page.getByRole('alert').waitFor();
    check(await page.getByRole('alert').innerText() === 'Thiếu mã giao dịch VNPay.', 'Missing reference gives useful error');
    await page.setViewportSize({ width: 1440, height: 1050 });
    await page.goto(base + '/account?section=tickets'); await page.locator('.myTicketCard').first().waitFor();
    check(await page.locator('.myTicketPoster img').count() === 4, 'My tickets history uses movie posters');
    check(await page.locator('.historyPaymentDetails[open]').count() === 0, 'Payment breakdown is collapsed by default');
    await page.screenshot({ path: path.join(artifacts, 'my-tickets-desktop.png'), fullPage: true });
    await Movie.updateOne({ _id: movie.id }, { $set: { title: 'Dune', poster: '/assets/posters/dune.jpg', banner: '/missing-backdrop.jpg' } });
    await page.goto(`${base}/bookings/${paid.booking.id}/tickets`); await page.locator('.cinemaSeatTicket').first().waitFor();
    await page.waitForFunction(() => document.querySelector('.cinemaPageBackdrop img')?.naturalWidth > 0);
    check(await page.locator('.cinemaHeroPoster img').evaluate(img => img.naturalWidth > 0), 'Legacy poster paths resolve to bundled artwork');
    check(await page.locator('.cinemaPageBackdrop img').getAttribute('src') !== '/missing-backdrop.jpg', 'Broken banner falls back to the booked movie poster');
    await Movie.updateOne({ _id: movie.id }, { $set: { title: 'Unknown movie' }, $unset: { poster: 1, banner: 1 } });
    await page.goto(`${base}/bookings/${paid.booking.id}/tickets`); await page.locator('.cinemaSeatTicket').first().waitFor();
    check(await page.locator('.cinemaHeroPoster img').count() === 0, 'Missing artwork uses visual fallback');
    await authenticate(employee); await page.goto(`${base}/payment-result?reference=${paid.ref}`);
    await page.locator('.cinemaSeatTicket').first().waitFor();
    check(await page.locator('.cinemaSeatTicket').count() === 2, 'Staff result preserves per-seat tickets');
    check(await page.getByRole('link', { name: 'Chi tiết vé & check-in →' }).count() === 0, 'Staff is not linked to member-only ticket route');
    const after = await Booking.findById(paid.booking.id).lean();
    check(after.total === before.total && after.paymentRef === before.paymentRef && after.status === before.status, 'Viewing redesigned pages never changes payment');
    check(after.tickets.map(t => t.reference).join() === before.tickets.map(t => t.reference).join(), 'Existing ticket references are preserved');
    check(errors.length === 0, 'No browser runtime errors: ' + errors.join('; '));
    console.log(`PASS: ${checks} ticket design UI checks. Screenshots: ${artifacts}`);
} catch (error) {
    if (page) { await mkdir(artifacts, { recursive: true }); await page.screenshot({ path: path.join(artifacts, 'failure.png'), fullPage: true }).catch(() => {}); }
    throw error;
} finally {
    await browser?.close(); await vite?.close(); if (server) await new Promise(resolve => server.close(resolve));
    assert.equal(mongoose.connection.name, dbName); await mongoose.connection.dropDatabase(); await mongoose.disconnect();
}
