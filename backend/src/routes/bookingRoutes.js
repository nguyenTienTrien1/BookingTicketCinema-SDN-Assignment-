import {start} from '../controllers/paymentController.js';
import { Router } from 'express';
import * as c from '../controllers/bookingController.js';
import { verifyToken } from '../middleware/auth/verifyToken.js';
import { requireRole } from '../middleware/auth/requireRole.js';
const r = Router();
r.use(verifyToken, requireRole('member'));
r.get('/', c.list);
r.post('/', c.create);
r.patch('/:id/points', c.points);
r.post('/:id/pay', start);
r.get('/:id', c.view);
r.patch('/:id/food', c.food);
r.post('/:id/cancel', c.cancel);
export default r;
