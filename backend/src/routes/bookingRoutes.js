import {start,result} from '../controllers/paymentController.js';
import { Router } from 'express';
import * as c from '../controllers/bookingController.js';
import { verifyToken } from '../middleware/auth/verifyToken.js';
import { requireRole } from '../middleware/auth/requireRole.js';
import { owned } from '../controllers/ticketController.js';
import { protectWrite } from '../controllers/ticketController.js';
import * as refunds from '../controllers/refundController.js';
const r = Router();
r.use(verifyToken, requireRole('member'));
r.get('/', c.list);
r.get('/:id/tickets', owned);
r.get('/:id/refund', refunds.preview);
r.post('/:id/refund', protectWrite, refunds.request);
r.get('/payment-result/:reference', result);
r.post('/', c.create);
r.post('/promotion-preview', protectWrite, c.promotionPreview);
r.patch('/:id/points', c.points);
r.patch('/:id/promotion', protectWrite, c.promotion);
r.post('/:id/pay', start);
r.get('/:id', c.view);
r.patch('/:id/food', c.food);
r.post('/:id/cancel', c.cancel);
export default r;
