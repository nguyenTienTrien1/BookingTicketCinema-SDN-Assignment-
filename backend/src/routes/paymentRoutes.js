import {Router} from 'express';
import {verifyToken} from '../middleware/auth/verifyToken.js';
import {requireRole} from '../middleware/auth/requireRole.js';
import * as p from '../controllers/paymentController.js';
import { protectWrite } from '../controllers/ticketController.js';
import * as refunds from '../controllers/refundController.js';
const r=Router();r.get('/vnpay/ipn',p.ipn);r.get('/vnpay/return',p.returnUrl);
r.use(verifyToken,requireRole('admin','employee'));
r.get('/results/:reference', p.result);
r.get('/tickets/:code',p.ticket);r.get('/bookings/:id',p.lookup);
r.post('/bookings/:id/cash', protectWrite, p.cash);
r.post('/bookings/:id/pay', protectWrite, p.staffPay);
r.patch('/members/:id/age',p.verifyAge);
r.get('/reconciliation', p.reconciliation);
r.get('/refunds', refunds.issues);
r.post('/refunds/:reference/retry', protectWrite, refunds.retry);
r.post('/reconciliation/:reference', protectWrite, p.resolvePayment);
r.get('/stock',requireRole('admin'),p.stock);r.patch('/stock/:id',requireRole('admin'),p.stock);
export default r;
