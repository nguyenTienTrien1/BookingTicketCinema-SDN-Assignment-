import 'dotenv/config';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import mongoose from 'mongoose';
import jwt from 'jsonwebtoken';
import { chromium } from 'playwright';
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import User from '../../src/models/users/User.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const artifacts = path.join(root, '.local/qa/adjust-points');
const dbName = 'cinema_adjust_points_ui_' + randomUUID().replaceAll('-', '');
process.env.NODE_ENV = 'test';
let server, vite, browser, page, checks = 0;
const check = (value, message) => { assert.ok(value, message); checks++; };
await mongoose.connect(process.env.MONGODB_URI, { dbName, serverSelectionTimeoutMS: 5000 });
try {
    const admin = await User.create({ fullName: 'Cinema Admin', email: 'admin@points-ui.test', password: randomUUID(), role: 'admin', status: 'Active' });
    const member = await User.create({ fullName: 'Nguyễn Minh Anh', email: 'minhanh@points-ui.test', phone: '0901234567', password: randomUUID(), role: 'member', status: 'Active', memberPoints: 120 });
    const other = await User.create({ fullName: 'Trần Hoàng Nam', email: 'hoangnam@points-ui.test', password: randomUUID(), role: 'member', status: 'Active', memberPoints: 35 });
    const { default: app } = await import('../../src/app.js');
    server = app.listen(0, '127.0.0.1'); await once(server, 'listening');
    vite = await createServer({ root: path.join(root, 'frontend'), configFile: false, plugins: [react()], logLevel: 'silent', define: { 'import.meta.env.VITE_API_URL': JSON.stringify('/api'), 'import.meta.env.VITE_GOOGLE_CLIENT_ID': JSON.stringify('') }, server: { host: '127.0.0.1', port: 0, proxy: { '/api': `http://127.0.0.1:${server.address().port}` } } });
    await vite.listen(); const base = `http://127.0.0.1:${vite.httpServer.address().port}`; process.env.CORS_ORIGIN = base;
    browser = await chromium.launch({ channel: process.env.E2E_BROWSER_CHANNEL || 'msedge', headless: true });
    const context = await browser.newContext({ viewport: { width: 1600, height: 1100 } });
    await context.addCookies([{ name: 'token', value: jwt.sign({ id: admin.id, tokenVersion: admin.tokenVersion || 0 }, process.env.JWT_SECRET || 'supersecret_cinema_jwt_key_2026_sdn302', { expiresIn: '5m' }), url: base, httpOnly: true }]);
    page = await context.newPage(); page.setDefaultTimeout(12000); const errors = []; page.on('pageerror', e => errors.push(e.message));
    await mkdir(artifacts, { recursive: true });
    await page.goto(base + '/account'); await page.getByRole('button', { name: 'Điều chỉnh điểm', exact: true }).click();
    await page.locator('.pointsWelcome').waitFor();
    await page.waitForFunction(() => document.querySelectorAll('.pointsMember').length === 2);
    check(await page.locator('.pointsMember').count() === 2, 'Only members appear');
    await page.getByRole('searchbox', { name: 'Tìm thành viên' }).fill('0901234567');
    check(await page.locator('.pointsMember').count() === 1, 'Search finds phone');
    await page.locator('.pointsMember').click(); await page.locator('.pointsEditor fieldset').waitFor();
    await page.waitForFunction(() => !document.querySelector('.pointsEditor fieldset').disabled);
    const amount = page.locator('#adjust-points-amount'), reason = page.locator('#adjust-points-reason');
    const submit = page.locator('.pointsSubmit');
    check(await submit.isDisabled(), 'Empty draft cannot submit');
    await amount.fill('10'); await reason.fill('Bù điểm giao dịch chưa được ghi nhận');
    check((await page.locator('.pointsPreview').innerText()).includes('130'), 'Preview adds points');
    await page.screenshot({ path: path.join(artifacts, 'desktop.png'), fullPage: true });
    async function save(status = 200) { const response = page.waitForResponse(r => r.url().endsWith(`/users/${member.id}/points`) && r.request().method() === 'PATCH'); await submit.click(); check((await response).status() === status, `Save HTTP ${status}`); await page.waitForFunction(() => !document.querySelector('.pointsEditor fieldset').disabled); }
    await save();
    check((await User.findById(member.id)).memberPoints === 130, 'Real API adds 10');
    check(await amount.inputValue() === '' && await reason.inputValue() === '', 'Success clears draft');
    check(await page.locator('.pointsHistoryList li').count() === 1, 'History updates automatically');
    await page.getByRole('button', { name: /Trừ điểm Thu hồi/ }).click(); await amount.fill('131'); await reason.fill('Thu hồi điểm cộng nhầm');
    check(await submit.isDisabled(), 'Overdraw cannot submit');
    check((await page.locator('#adjust-points-help').innerText()).includes('vượt số dư'), 'Overdraw has clear inline explanation');
    await amount.fill('5'); await save(); check((await User.findById(member.id)).memberPoints === 125, 'Subtract sends negative delta');
    await amount.fill('0'); check(await submit.isDisabled(), 'Zero cannot submit');
    await amount.fill('5'); await reason.fill('abc'); check(await submit.isDisabled(), 'Short reason cannot submit');
    check((await page.locator('#adjust-reason-help').innerText()).includes('Hiện có 3 ký tự'), 'Short reason explains why confirmation is disabled');
    check(await reason.getAttribute('aria-invalid') === 'true', 'Invalid reason is marked on its field');
    await reason.fill('Điều chỉnh sau đối soát');
    await User.updateOne({ _id: member.id }, { $set: { memberPoints: 150 } });
    await save(409); check(await amount.inputValue() === '5', 'Stale failure preserves draft');
    await page.getByRole('button', { name: /Làm mới số dư/ }).click(); await page.waitForFunction(() => !document.querySelector('.pointsEditor fieldset').disabled);
    check((await page.locator('.pointsCurrentBalance').innerText()).includes('150'), 'Refresh reads new balance');
    await save(); check((await User.findById(member.id)).memberPoints === 145, 'Retry uses refreshed expected balance');
    await page.getByRole('button', { name: /Cộng điểm Bù/ }).click(); await amount.fill('7'); await reason.fill('Bù điểm khi kết nối gián đoạn');
    await page.route(`**/users/${member.id}/points`, async route => { await route.fetch(); await route.abort(); }, { times: 1 });
    await submit.click(); await page.locator('.pointsEditor [role=alert]').waitFor();
    check((await User.findById(member.id)).memberPoints === 152, 'Simulated lost response committed once');
    await save(); check((await User.findById(member.id)).memberPoints === 152, 'Retry does not add twice');
    check((await User.findById(member.id).select('+pointAdjustments')).pointAdjustments.length === 4, 'Each unique adjustment has one audit entry');
    await page.getByRole('searchbox', { name: 'Tìm thành viên' }).fill('');
    await amount.fill('9'); await reason.fill('Bản nháp của Minh Anh');
    await page.locator('.pointsMember').filter({ hasText: other.email }).click(); await page.waitForFunction(() => !document.querySelector('.pointsEditor fieldset').disabled);
    check(await amount.inputValue() === '', 'Member drafts are separate');
    check((await page.locator('.pointsCurrentBalance').innerText()).includes('35'), 'Selected member gets correct balance');
    await page.locator('.pointsMember').filter({ hasText: member.email }).click(); await page.waitForFunction(() => !document.querySelector('.pointsEditor fieldset').disabled);
    check(await amount.inputValue() === '9', 'Returning restores that member draft');
    for (const width of [390, 360]) { await page.setViewportSize({ width, height: 844 }); check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Layout fits ${width}px`); }
    await page.screenshot({ path: path.join(artifacts, 'mobile.png'), fullPage: true });
    check(errors.length === 0, 'No runtime errors: ' + errors.join('; '));
    console.log(`PASS: ${checks} admin point adjustment UI checks. Screenshots: ${artifacts}`);
} catch (error) {
    if (page) await page.screenshot({ path: path.join(artifacts, 'failure.png'), fullPage: true }).catch(() => {});
    throw error;
} finally {
    await browser?.close(); await vite?.close(); if (server) await new Promise(resolve => server.close(resolve));
    assert.equal(mongoose.connection.name, dbName); await mongoose.connection.dropDatabase(); await mongoose.disconnect();
}
